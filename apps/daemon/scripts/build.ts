// Builds the single `pier` binary: the web app is built, every file in it is embedded, and the
// daemon is compiled with Bun. The result needs nothing installed except gh and git.
//
//   bun run build            -> apps/daemon/dist/pier

import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const daemon = join(import.meta.dir, "..");
const web = join(daemon, "..", "web");
const webDist = join(web, "dist");
const buildDir = join(daemon, ".build");
const out = join(daemon, "dist", "pier");

function run(cmd: string[], cwd: string) {
  const result = Bun.spawnSync(cmd, { cwd, stdout: "inherit", stderr: "inherit" });
  if (result.exitCode !== 0) throw new Error(`${cmd.join(" ")} failed (${result.exitCode})`);
}

run(["bun", "run", "build"], web);

// One import per built file, each embedded as a file and mapped from its URL path.
const files = [...new Bun.Glob("**/*").scanSync({ cwd: webDist, dot: false })].toSorted();
rmSync(buildDir, { recursive: true, force: true });
mkdirSync(buildDir, { recursive: true });
const imports = files.map(
  (file, i) =>
    `import f${i} from ${JSON.stringify(relative(buildDir, join(webDist, file)))} with { type: "file" };`,
);
const entries = files.map((file, i) => `  [${JSON.stringify(`/${file}`)}, f${i}],`);
writeFileSync(
  join(buildDir, "entry.ts"),
  `// Generated by scripts/build.ts. Do not edit.
${imports.join("\n")}
import { registerEmbeddedAssets } from "../src/http/assets";

registerEmbeddedAssets(new Map<string, string>([
${entries.join("\n")}
]));

await import("../src/main");
`,
);

mkdirSync(join(daemon, "dist"), { recursive: true });
run(
  [
    "bun",
    "build",
    "--compile",
    "--minify",
    "--sourcemap",
    join(buildDir, "entry.ts"),
    "--outfile",
    out,
  ],
  daemon,
);
rmSync(buildDir, { recursive: true, force: true });
console.log(`\nbuilt ${relative(process.cwd(), out)} with ${files.length} embedded web files`);
